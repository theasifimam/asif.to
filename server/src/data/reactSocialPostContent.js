export function buildReactSocialPost(topic, index = 0) {
  const content = REACT_SOCIAL_POST_CONTENT[topic];
  if (!content) throw new Error(`Missing social-post content for: ${topic}`);

  return {
    name: `${topic} - Tutorial`,
    caption: `Learn ${topic} with a precise definition, a practical example, and one mistake to avoid. Swipe through and save it for later.`,
    hashtags: ["reactjs", "webdev", "frontend", "javascript", "coding"],
    slides: [
      { id: `slide-${index}-cover`, order: 0, template: "tutorial-cover", eyebrow: "React & Next.js", title: topic, subtitle: "Definition, working example, and best practice", badge: "Tutorial" },
      { id: `slide-${index}-def`, order: 1, template: "definition", eyebrow: "Core Concept", title: `What is ${topic}?`, body: content.definition, highlightedText: content.takeaway },
      { id: `slide-${index}-code`, order: 2, template: "code-snippet", title: "Practical Example", subtitle: "A focused example of the concept", code: { language: "javascript", filename: content.filename, content: content.code, highlightLines: [], showLineNumbers: true } },
      { id: `slide-${index}-tip`, order: 3, template: "developer-tip", eyebrow: "Best Practice", title: "Use It Correctly", body: content.tip, highlightedText: content.takeaway, badge: "Tip" },
      { id: `slide-${index}-summary`, order: 4, template: "summary", title: "Remember This", body: content.takeaway, cta: "Learn more at asif.to/reactjs", url: "https://asif.to/reactjs" },
    ],
  };
}
